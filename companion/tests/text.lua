for k in pairs(_G) do assert(before[k], "Text.lua left a global: " .. tostring(k)) end

local function eq(got, want, what)
    if got ~= want then error(("%s: got %q, want %q"):format(what or "", tostring(got), tostring(want)), 2) end
end

